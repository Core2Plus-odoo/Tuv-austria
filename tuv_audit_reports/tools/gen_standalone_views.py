#!/usr/bin/env python3
"""Write views/standalone_blocks.xml from views/forms/*.xml.

Every audit form is shown in two places: on the project (Audit Plan tab) and on its
standalone record opened from the Reports card (model tuv.audit.plan). Both models carry
the same field names, so the block of a form is written once, for the project, in
views/forms/<form>.xml; this script copies each block to the standalone form view.

Run it after changing anything in views/forms/, from the module folder:
    python3 tools/gen_standalone_views.py
Not loaded by Odoo (not a Python package of the module).
"""
import ast
import copy
import pathlib

from lxml import etree

MODULE = pathlib.Path(__file__).resolve().parent.parent
PROJECT_TAB = 'tuv_audit_reports.edit_project_audit_plan_tab'
STANDALONE_FORM = 'tuv_audit_reports.tuv_audit_plan_view_form'


def main():
    out = etree.Element('odoo')
    out.text = '\n\n    '
    out.append(etree.Comment(
        ' GENERATED by tools/gen_standalone_views.py from views/forms/*.xml - do not edit by hand. '))
    out[-1].tail = '\n\n    '
    # only the block files the manifest loads (a file being written is not ready yet)
    manifest = ast.literal_eval((MODULE / '__manifest__.py').read_text())
    loaded = [MODULE / f for f in manifest['data'] if f.startswith('views/forms/')]
    for path in loaded:
        tree = etree.parse(str(path), etree.XMLParser(remove_blank_text=False))
        for record in tree.iterfind('.//record[@model="ir.ui.view"]'):
            inherit = record.find('field[@name="inherit_id"]')
            if inherit is None or inherit.get('ref') != PROJECT_TAB:
                continue
            twin = copy.deepcopy(record)
            twin.set('id', record.get('id') + '_standalone')
            twin.find('field[@name="name"]').text = (
                record.find('field[@name="name"]').text.replace('project.project', 'tuv.audit.plan'))
            twin.find('field[@name="model"]').text = 'tuv.audit.plan'
            twin.find('field[@name="inherit_id"]').set('ref', STANDALONE_FORM)
            twin.tail = '\n\n    '
            out.append(twin)
    out[-1].tail = '\n\n'
    target = MODULE / 'views' / 'standalone_blocks.xml'
    target.write_bytes(etree.tostring(out, encoding='utf-8', xml_declaration=True) + b'\n')
    print('wrote', target, '-', len(out) - 1, 'views')


if __name__ == '__main__':
    main()
